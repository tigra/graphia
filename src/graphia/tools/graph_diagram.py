"""Generate docs/langgraph-topology.generated.md from the compiled graph (``make graph-diagram``).

The hand-maintained ``docs/langgraph-topology.mermaid`` explains the graph (state shape,
what each node does, which LLM it calls) but can drift as nodes are added. This
file is the drift-proof companion: it compiles the real topology through the
same ``_assemble_graph`` both run modes use, and writes LangGraph's own Mermaid
rendering of it. Every node and edge is the graph's own; conditional edges are
dashed. No model, no AWS, no checkpoint file: the checkpointer is in-memory and
the injected services are never called while compiling.
"""

from __future__ import annotations

import argparse
import sqlite3
from pathlib import Path

from langgraph.checkpoint.sqlite import SqliteSaver

from graphia.graph import _assemble_graph, make_checkpoint_serde

DEFAULT_OUT = Path(__file__).resolve().parents[3] / "docs" / "langgraph-topology.generated.md"

HEADER = """\
# Graphia graph topology (generated)

<!-- Generated by `make graph-diagram` from the compiled graph. Do not edit by hand. -->

This is the compiled LangGraph `StateGraph`, rendered by LangGraph itself from the
same `_assemble_graph` that local and hosted modes use, so it cannot drift from
the code. Solid arrows are plain edges; dashed arrows are conditional edges.
For what each node does, the state it writes and the LLMs it calls, see the
hand-maintained [`langgraph-topology.mermaid`](langgraph-topology.mermaid).
Regenerate with `make graph-diagram`.

"""


def render() -> str:
    """Return LangGraph's Mermaid source for the game graph."""
    saver = SqliteSaver(
        sqlite3.connect(":memory:", check_same_thread=False),
        serde=make_checkpoint_serde(),
    )
    graph = _assemble_graph(
        diary_store=None,  # bound into node partials only; never called here
        career_emitter=None,
        game_id="graph-diagram",
        saver=saver,
        recap_enabled=True,
        recap_aware_reasoning_enabled=True,
    )
    return pin_theme(graph.get_graph().draw_mermaid())


# Pinned theme, mirroring docs/langgraph-topology.mermaid (whose header comments
# explain each part). Without it, anything Mermaid paints itself follows the
# VIEWER's theme, so a dark-mode IDE preview turns labels light grey. Text colour
# needs BOTH mechanisms: classDef carries node labels; themeCSS (top level, a
# sibling of theme) carries edge labels and the subgraph title. The init
# directive must be the diagram's first line.
INIT = (
    "%%{init: {'theme':'base','flowchart':{'curve':'linear'},"
    "'themeCSS':'span,p,text,tspan{color:#000000!important;fill:#000000!important;}"
    ".nodeLabel,.nodeLabel span,.nodeLabel p,.edgeLabel,.edgeLabel span,.edgeLabel p,"
    ".cluster-label,.cluster-label span,.cluster-label p,.label,.label span,.label p"
    "{color:#000000!important;fill:#000000!important;}',"
    "'themeVariables':{'background':'#ffffff','fontFamily':'ui-sans-serif, system-ui, sans-serif',"
    "'fontSize':'14px','textColor':'#000000','primaryTextColor':'#000000',"
    "'secondaryTextColor':'#000000','tertiaryTextColor':'#000000','nodeTextColor':'#000000',"
    "'titleColor':'#000000','lineColor':'#000000','edgeLabelBackground':'#ffffff',"
    "'labelBackground':'#ffffff','clusterBkg':'#adb5bd','clusterBorder':'#343a40'}}}%%"
)
CLASS_DEFS = (
    "classDef node fill:#d3f9d8,stroke:#000000,stroke-width:2px,color:#000000",
    "classDef first fill:#e9ecef,stroke:#000000,stroke-width:2px,color:#000000",
    "classDef last fill:#e9ecef,stroke:#000000,stroke-width:2px,color:#000000",
)


def pin_theme(mermaid: str) -> str:
    """Restyle LangGraph's Mermaid output to read the same in light and dark viewers.

    Swaps LangGraph's front-matter config and class styles for the pinned theme,
    and puts the whole graph on a grey plate (a subgraph): black edges on a dark
    page would otherwise vanish.
    """
    lines = mermaid.strip().splitlines()
    if lines and lines[0].strip() == "---":  # drop the front-matter config block
        lines = lines[lines.index("---", 1) + 1:]
    body = []
    for raw in lines:
        line = raw.strip()
        if not line or line.startswith(("graph ", "classDef ")):
            continue
        # A node declaration (no arrow, no class yet) gets the `node` class.
        # Styling `default` instead would also paint the plate subgraph green.
        if "-->" not in line and "-.->" not in line and ":::" not in line:
            line += ":::node"
        body.append(line)
    plate = "\n".join(f"        {line}" for line in body)
    styles = "\n".join(f"    {line}" for line in CLASS_DEFS)
    return (
        f"{INIT}\nflowchart TB\n{styles}\n"
        f'    subgraph GRAPH ["StateGraph(GameState), as compiled"]\n'
        f"        direction TB\n{plate}\n    end\n"
        f"    linkStyle default stroke:#000000,stroke-width:2px\n"
    )


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(
        prog="graphia.tools.graph_diagram",
        description="Write the compiled game graph's topology as Mermaid in Markdown.",
    )
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = parser.parse_args(argv)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(f"{HEADER}```mermaid\n{render().rstrip()}\n```\n", encoding="utf-8")
    print(f"Wrote {args.out}")


if __name__ == "__main__":
    main()
